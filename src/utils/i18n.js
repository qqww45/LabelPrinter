export function useI18n() {
  /**
   * 翻译 + 占位替换：t('模板中用了 {n} 个字段', { n: 5 })
   * 占位语法：{key}，与 Vue 模板插值 {{}} 不冲突
   * 未收录的字符串原样返回（中文环境下零成本）
   */
  const t = (s, params) => {
    let out = lang.value === 'en' ? (EN[s] || s) : s
    if (params && typeof params === 'object') {
      out = out.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`))
    }
    return out
  }
  return { t, lang }
}
